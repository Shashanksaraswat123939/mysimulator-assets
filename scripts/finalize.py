"""Merges per-group outputs: manifest.json, RESOURCES.md and contact sheets. python3 finalize.py <merged_dir>"""
import glob, json, os, subprocess, sys
D = sys.argv[1]
man = []
for f in sorted(glob.glob(os.path.join(D, "manifest_*.json"))):
    man += json.load(open(f))
json.dump(man, open(os.path.join(D, "manifest.json"), "w"), indent=1)
ok = [m for m in man if m.get("status") != "FAILED"]
bad = [m for m in man if m.get("status") == "FAILED"]
groups = {}
for m in ok:
    groups.setdefault(m["group"], []).append(m)
os.makedirs(os.path.join(D, "sheets"), exist_ok=True)
for g, items in groups.items():
    files = [os.path.join(D, p) for m in items for p in m["previews"]]
    files = [f for f in files if os.path.exists(f)]
    if not files:
        continue
    subprocess.run(["montage", "-label", "%t", "-pointsize", "16", "-background", "#16181b", "-fill", "#e6e8ea", "-tile", "3x", "-geometry", "640x360+6+6"] + files + [os.path.join(D, "sheets", "sheet_%s.jpg" % g)], check=False)
lines = ["# My Simulator: asset resources", "", "Generated by CI from `scripts/`. Every mesh below is original geometry built in code (Blender 5.2.2 data API). "
         "No third-party meshes, textures, fonts or audio are used.", "", "## Tools", "- Blender 5.2.2 (headless, Cycles CPU) builds, colours, exports and renders every asset.",
         "- Fonts: Blender's built-in default font only, used for numbers and labels.", "- Materials: procedural Principled BSDF colours; no image textures yet.",
         "- Audio: none yet (see below).", "", "## Assets"]
for g, items in groups.items():
    lines += ["", "### %s" % g, "", "| asset | meshes | triangles | materials | FBX |", "|---|---|---|---|---|"]
    for m in items:
        lines.append("| %s | %d | %d | %s | %s |" % (m["name"], m["meshes"], m["triangles"], ", ".join(m["materials"][:8]) + (" ..." if len(m["materials"]) > 8 else ""), m["fbx"] or "n/a"))
if bad:
    lines += ["", "## Failed builds", ""] + ["- %s" % m["name"] for m in bad]
lines += ["", "## Still missing (not built, not sourced)", "- Rigged pit-crew animation (models are jointed and ready), wheel-gun spin, jack lift.",
          "- All audio: guns, engines, tyres, crowd, engineer voice. Candidate sources to licence-check: Freesound (CC0 only), Kenney (CC0).",
          "- Real track geometry for the pit lane; the pit lane here is a standalone strip.", "- Collision meshes and LODs.", "- Liveries are colour schemes on geometry; no decal/UV paint system yet."]
open(os.path.join(D, "RESOURCES.md"), "w").write("\n".join(lines))
print("assets ok:", len(ok), "failed:", len(bad))
